import { newId } from "./storage.js";

// --- 患者情報の入力項目（カルテ番号つき・全テンプレ共通） ---
// ※「申込日・店舗名・担当者名」は入力画面に最初から付いているので、ここには入れません。
function karadaFields(extra = []) {
  return [
    { id: newId(), label: "カルテ番号", type: "text", required: false, placeholder: "例: 12345" },
    { id: newId(), label: "お客様氏名", type: "text", required: true, placeholder: "山田 太郎" },
    { id: newId(), label: "フリガナ", type: "text", required: false, placeholder: "ヤマダ タロウ" },
    { id: newId(), label: "生年月日", type: "date", required: false, placeholder: "" },
    { id: newId(), label: "電話番号", type: "tel", required: false, placeholder: "090-1234-5678" },
    { id: newId(), label: "住所", type: "text", required: false, placeholder: "" },
    ...extra,
    { id: newId(), label: "備考", type: "textarea", required: false, placeholder: "" },
  ];
}

// チェック項目を作る小さなヘルパー
function chk(label) {
  return { id: newId(), label };
}

// テンプレートを1件作るヘルパー
function tpl({ name, category, body, plans, checks, fields }) {
  return {
    id: newId(),
    name,
    category,
    bodyText: body,
    fields: fields || karadaFields(),
    plans: plans || [],
    checks,
    terms: "", // このテンプレートでは確認チェック項目に規約内容を含めています
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };
}

